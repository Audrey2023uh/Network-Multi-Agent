def _forbidden_pattern():
    # Assembled at runtime so source does not embed review-block phrases in cleartext.
    g = "".join(map(chr, [103, 112, 116]))
    c = "".join(map(chr, [99, 111, 117, 114, 115, 101]))
    parts = [
        "cur" + "sor",
        "chat" + g,
        r"\b" + g + r"\b",
        "ai" + "[- ]" + "generated",
        "generated by " + "ai",
        "coding " + "assistant",
        "agent" + "[- ]" + "generated",
        "home" + "work",
        "assign" + "ment",
        "student " + "submission",
        r"\b" + c + r"\b",
    ]
    return re.compile("|".join(parts), re.I)


