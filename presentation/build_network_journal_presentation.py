def set_run(run, text, size=18, bold=False, color=DARK, font="Calibri"):
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run.font.name = font


def add_textbox(slide, left, top, width, height, text, size=18, bold=False,
                color=DARK, align=PP_ALIGN.LEFT, font="Calibri"):
    box = slide.shapes.add_textbox(left, top, width, height)
    tf = box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = align
    set_run(p.add_run() if p.runs else p.runs[0] if False else _ensure_run(p),
            text, size=size, bold=bold, color=color, font=font)
    # fix: pptx paragraphs always have one empty run sometimes
    return box


def _ensure_run(p):
    if not p.runs:
        return p.add_run()
    return p.runs[0]


def title_bar(slide, title: str, subtitle: str | None = None):
    shape = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), W, Inches(1.05))
    shape.fill.solid()
    shape.fill.fore_color.rgb = NAVY
    shape.line.fill.background()
    tb = slide.shapes.add_textbox(Inches(0.45), Inches(0.22), Inches(12.4), Inches(0.55))
    p = tb.text_frame.paragraphs[0]
    set_run(_ensure_run(p), title, size=26, bold=True, color=WHITE)
    if subtitle:
        tb2 = slide.shapes.add_textbox(Inches(0.45), Inches(0.68), Inches(12.4), Inches(0.32))
        p2 = tb2.text_frame.paragraphs[0]
        set_run(_ensure_run(p2), subtitle, size=12, color=RGBColor(0xC8, 0xD8, 0xE4))


def footer(slide, page: int, total: int):
    tb = slide.shapes.add_textbox(Inches(0.4), Inches(7.15), Inches(10), Inches(0.28))
    p = tb.text_frame.paragraphs[0]
    set_run(_ensure_run(p), "ECNetBench · Enterprise Cognitive Network (ECN-v3)", size=10, color=SLATE)
    tb2 = slide.shapes.add_textbox(Inches(11.5), Inches(7.15), Inches(1.5), Inches(0.28))
    p2 = tb2.text_frame.paragraphs[0]
    p2.alignment = PP_ALIGN.RIGHT
    set_run(_ensure_run(p2), f"{page} / {total}", size=10, color=SLATE)


def bullets(slide, left, top, width, height, items, size=16):
    box = slide.shapes.add_textbox(left, top, width, height)
    tf = box.text_frame
    tf.word_wrap = True
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.level = 0
        p.space_after = Pt(8)
        set_run(_ensure_run(p), "•  " + item, size=size, color=DARK)
    return box


def add_picture_safe(slide, path: Path, left, top, width=None, height=None):
    if not path.exists():
        raise FileNotFoundError(path)
    kwargs = {}
    if width is not None:
        kwargs["width"] = width
    if height is not None:
        kwargs["height"] = height
    return slide.shapes.add_picture(str(path), left, top, **kwargs)


